const CampaignWaveDefinition* find_campaign_wave(std::int32_t mission_id) noexcept {
    const CampaignWaveDefinition* found=nullptr;
    for (const CampaignWaveDefinition& wave : kWaves)
        if (wave.mission_id==mission_id) found=&wave;
    return found;
}

const CampaignWaveDefinition* next_campaign_wave(const CampaignWaveDefinition& wave) noexcept {
    if (!wave.next_wave_index || *wave.next_wave_index>=kWaves.size()) return nullptr;
    return &kWaves[*wave.next_wave_index];
}

const CampaignWaveDefinition* campaign_wave_for_record(const CampaignRecord& record) noexcept {
    return find_campaign_wave(static_cast<std::int32_t>(record.mission_id));
}

std::optional<std::array<std::int16_t,4>> campaign_gun_table(std::uint32_t vram) noexcept {
    if (vram<campaign_gun_table_vram || (vram-campaign_gun_table_vram)%8U!=0U) return std::nullopt;
    const std::uint32_t slot=(vram-campaign_gun_table_vram)/8U;
    if (slot>=kGunTables.size()) return std::nullopt;
    return kGunTables[slot];
}

CampaignOwnerPopulation endurance_owner_population(std::int32_t kills,std::uint8_t owner) noexcept {
    std::int32_t share=0;
    switch (owner) {
    case 1: share=kills/3+(kills%3>0 ? 1 : 0); break;
    case 2: share=kills/3+(kills%3>=2 ? 1 : 0); break;
    case 3: share=kills/3; break;
    default: return CampaignOwnerPopulation{5,0}; // owner 0 keeps setup.lives=5
    }
    if (share<4) return CampaignOwnerPopulation{share,0};
    return CampaignOwnerPopulation{3,share-3};
}

void CampaignWaveLaunch::serialize(StateWriter& out) const {
    out.u8(wave_index);
    out.s32(game_kind);
    out.s32(world_stream);
    out.s32(player_unit_kind);
    out.u8(skill_group);
    out.u16(player_bonus);
    out.s32(player_score);
}

CampaignWaveLaunch make_campaign_wave_launch(const CampaignWaveDefinition& wave,
    std::int32_t carry,std::int16_t bonus,std::uint8_t skill_group,std::int32_t selected_unit_kind) noexcept {
    CampaignWaveLaunch launch;
    launch.wave_index=wave.wave_index;
    launch.game_kind=wave.game_kind;
    launch.world_stream=wave.world_stream;
    launch.player_unit_kind=wave.player_unit_from_selection ? selected_unit_kind : wave.player_unit_kind;
    launch.skill_group=skill_group;
    // u16 field += s16 bonus, wrapping as the original halfword store does.
    launch.player_bonus=static_cast<std::uint16_t>(wave.player_bounds[0]+static_cast<std::uint16_t>(bonus));
    launch.player_score=static_cast<std::int32_t>(static_cast<std::uint32_t>(wave.owners[0].initial_score)
        +static_cast<std::uint32_t>(carry));
    return launch;
}

CampaignCatalogAudit audit_campaign_catalog() {
    CampaignCatalogAudit audit;
    audit.wave_count=kWaves.size();
    if (kWaves.size()!=17U) audit.issues.push_back({CampaignCatalogIssueCode::wrong_wave_count,0U});
    const auto streams=level_stream_descriptors();
    for (std::size_t i=0U; i<kWaves.size(); ++i) {
        const CampaignWaveDefinition& wave=kWaves[i];
        const auto at=static_cast<std::uint8_t>(i);
        bool unique=true;
        for (std::size_t j=0U; j<kWaves.size(); ++j)
            if (j!=i && kWaves[j].mission_id==wave.mission_id) unique=false;
        if (unique) ++audit.unique_mission_ids;
        else audit.issues.push_back({CampaignCatalogIssueCode::duplicate_mission_id,at});
        if (wave.wave_index!=i) audit.issues.push_back({CampaignCatalogIssueCode::wave_index_mismatch,at});
        const LevelStreamDescriptor* stream=nullptr;
        for (const LevelStreamDescriptor& d : streams) if (d.index==wave.world_stream) stream=&d;
        if (stream==nullptr) audit.issues.push_back({CampaignCatalogIssueCode::world_stream_out_of_range,at});
        else if (stream->navigation.has_value()!=wave.navigation_available || !wave.navigation_available)
            audit.issues.push_back({CampaignCatalogIssueCode::navigation_missing,at});
        if (wave.next_wave_index && (*wave.next_wave_index>=kWaves.size() || *wave.next_wave_index!=i+1U))
            audit.issues.push_back({CampaignCatalogIssueCode::transition_outside_catalog,at});
        if (!wave.next_wave_index && i+1U!=kWaves.size())
            audit.issues.push_back({CampaignCatalogIssueCode::transition_outside_catalog,at});
        if (wave.objective==CampaignObjectiveKind::unresolved)
            audit.issues.push_back({CampaignCatalogIssueCode::objective_unresolved,at});
        else ++audit.resolved_objectives;
        if (wave.owner_count<1 || wave.owner_count>static_cast<std::int32_t>(campaign_owner_slots))
            audit.issues.push_back({CampaignCatalogIssueCode::owner_count_out_of_range,at});
        bool guns=true;
        for (const CampaignOwnerSetup& owner : wave.owners)
            for (const CampaignSkillProfile& skill : owner.skills)
                for (std::uint32_t ptr : {skill.gun_damage_vram,skill.gun_fire_rate_vram})
                    if (ptr!=0U && !campaign_gun_table(ptr)) guns=false;
        if (!guns) audit.issues.push_back({CampaignCatalogIssueCode::gun_table_missing,at});
        if (wave.briefing_image<0 || wave.briefing_image>=17)
            audit.issues.push_back({CampaignCatalogIssueCode::briefing_image_out_of_range,at});
        if (wave.chapter_sequence) ++audit.chapter_starts;
        if (wave.objective==CampaignObjectiveKind::endurance) ++audit.endurance_waves;
    }
    return audit;
}

