// The word that follows the table (ROM 0x0D520C). After the 17th wave
// clears, run_campaign_waves reads gOpponentWaves[17].id from here and
// func_800D0828 stores its low byte as the next mission id.
constexpr std::uint32_t kPostTableIdWord=0x3F000000U;

constexpr std::uint32_t word(const CampaignRawWave& raw,std::size_t offset) noexcept { return raw[offset/4U]; }
constexpr std::int32_t sword(const CampaignRawWave& raw,std::size_t offset) noexcept {
    return std::bit_cast<std::int32_t>(word(raw,offset));
}
constexpr std::uint8_t byte(const CampaignRawWave& raw,std::size_t offset) noexcept {
    return static_cast<std::uint8_t>(word(raw,offset&~std::size_t{3U})>>(24U-8U*(offset&3U)));
}
constexpr std::uint16_t half(const CampaignRawWave& raw,std::size_t offset) noexcept {
    return static_cast<std::uint16_t>(word(raw,offset&~std::size_t{3U})>>(16U-8U*(offset&2U)));
}

// select_screen_transition (func_8007D2A0) switch on the level id.
constexpr std::int8_t music_transition_for(std::int32_t level) noexcept {
    switch (level) {
    case 0: return -1;
    case 1: return 7;
    case 2: return 2;
    case 4: return 0x11;
    case 6: return 3;
    case 7: return 1;
    case 8: return 0x12;
    case 10: return 0x10;
    case 11: return 4;
    case 12: return 5;
    case 14: return 8;
    case 16: return 0xA;
    case 5: case 9: case 13: case 15: case 17: return 6;
    case 18: case 19: return -1; // no change: keeps the previous transition
    default: return 0;
    }
}

// run_campaign_waves: cut-scene sequence before chapter openers.
constexpr std::optional<std::uint8_t> chapter_for(std::size_t index) noexcept {
    switch (index) {
    case 0: return std::uint8_t{15U};
    case 5: return std::uint8_t{16U};
    case 9: return std::uint8_t{17U};
    case 13: return std::uint8_t{18U};
    default: return std::nullopt;
    }
}

constexpr CampaignSkillProfile decode_skill(const CampaignRawWave& raw,std::size_t group,std::size_t owner) noexcept {
    const std::size_t base=0x1CU+(group*campaign_owner_slots+owner)*campaign_skill_profile_size;
    CampaignSkillProfile skill;
    skill.aggressiveness=std::bit_cast<float>(word(raw,base));
    skill.intelligence=std::bit_cast<float>(word(raw,base+0x04U));
    skill.offense=sword(raw,base+0x08U);
    skill.defense=sword(raw,base+0x0CU);
    skill.gun_resurrection=sword(raw,base+0x10U);
    skill.gun_damage_vram=word(raw,base+0x14U);
    skill.gun_fire_rate_vram=word(raw,base+0x18U);
    for (std::size_t i=0U; i<skill.tint.size(); ++i) skill.tint[i]=byte(raw,base+0x1CU+i);
    return skill;
}

constexpr CampaignWaveDefinition decode_wave(std::size_t index) noexcept {
    const CampaignRawWave& raw=kRawWaves[index];
    CampaignWaveDefinition wave;
    wave.wave_index=static_cast<std::uint8_t>(index);
    wave.game_kind=sword(raw,0x000U);
    wave.mission_id=sword(raw,0x004U);
    wave.raw_field_08=sword(raw,0x008U);
    wave.player_unit_kind=sword(raw,0x00CU);
    wave.player_unit_from_selection=wave.game_kind!=7;
    wave.world_stream=static_cast<std::uint8_t>(wave.mission_id);
    // Cross-checked against level_stream_descriptors() by the audit.
    wave.navigation_available=wave.mission_id>=1 && wave.mission_id<=17;
    wave.objective=objective_for_game_kind(wave.game_kind);
    wave.view_mode=sword(raw,0x1CCU);
    wave.countdown_unit=wave.view_mode==1 ? 24U : 18U;
    wave.resets_team_counters=wave.game_kind==0 || wave.game_kind==3 || wave.game_kind==4 || wave.game_kind==6;
    wave.owner_count=sword(raw,0x1D0U);
    for (std::size_t owner=0U; owner<campaign_owner_slots; ++owner) {
        CampaignOwnerSetup& setup=wave.owners[owner];
        setup.unit_kind=sword(raw,0x00CU+4U*owner);
        setup.team=sword(raw,0x1D4U+4U*owner);
        setup.computer_controlled=wave.view_mode==1 && owner!=0U;
        setup.initial_score=sword(raw,0x1E4U+4U*owner);
        setup.reserve=sword(raw,0x1F4U+4U*owner);
        for (std::size_t group=0U; group<campaign_skill_groups; ++group)
            setup.skills[group]=decode_skill(raw,group,owner);
    }
    wave.raw_field_204=sword(raw,0x204U);
    wave.endurance_kills=sword(raw,0x208U);
    for (std::size_t i=0U; i<wave.player_bounds.size(); ++i) wave.player_bounds[i]=half(raw,0x20CU+2U*i);
    for (std::size_t i=0U; i<wave.scene_rgb.size(); ++i) wave.scene_rgb[i]=byte(raw,0x214U+i);
    wave.par_time_seconds=sword(raw,0x218U);
    wave.raw_field_21C=word(raw,0x21CU);
    wave.music_transition=music_transition_for(wave.mission_id);
    wave.briefing_image=wave.mission_id>=0 && wave.mission_id<18
        ? kBriefingIndices[static_cast<std::size_t>(wave.mission_id)] : -1;
    wave.chapter_sequence=chapter_for(index);
    if (index+1U<campaign_wave_count) {
        wave.next_wave_index=static_cast<std::uint8_t>(index+1U);
        wave.saved_mission_id_after_clear=static_cast<std::uint8_t>(word(kRawWaves[index+1U],0x004U));
    } else {
        wave.saved_mission_id_after_clear=static_cast<std::uint8_t>(kPostTableIdWord);
    }
    wave.advances_on_failure=wave.game_kind==7;
    wave.save_prompt_after_win=wave.game_kind==7 || wave.mission_id!=0x10;
    return wave;
}

constexpr std::array<CampaignWaveDefinition,campaign_wave_count> build_waves() noexcept {
    std::array<CampaignWaveDefinition,campaign_wave_count> waves{};
    for (std::size_t i=0U; i<campaign_wave_count; ++i) waves[i]=decode_wave(i);
    return waves;
}

constexpr std::array<CampaignWaveDefinition,campaign_wave_count> kWaves=build_waves();

constexpr bool ids_unique() noexcept {
    for (std::size_t i=0U; i<kWaves.size(); ++i)
        for (std::size_t j=i+1U; j<kWaves.size(); ++j)
            if (kWaves[i].mission_id==kWaves[j].mission_id) return false;
    return true;
}

constexpr bool objectives_resolved() noexcept {
    for (const CampaignWaveDefinition& wave : kWaves)
        if (wave.objective==CampaignObjectiveKind::unresolved) return false;
    return true;
}

